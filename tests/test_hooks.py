"""Tests for the lifecycle-hook engine and its wiring into the config loader.

The host renders ``~/.config/tartarus/hooks.toml`` at rebuild time
(``nix/host/hooks.nix``) and the CLI reads it back around every lifecycle
operation. This file covers the runtime half: parsing that file
(:func:`tartarus.hooks.load_hooks`), the ``--hooks`` / ``TARTARUS_HOOKS`` /
sibling-of-config path precedence in :func:`tartarus.config.load_config`, the
guest/kind/event/phase filtering (:meth:`tartarus.hooks.Hook.matches` and
:meth:`tartarus.config.Config.hooks_for`), token substitution, and the
retry/``warn``/``abort``/timeout behaviour of :func:`tartarus.hooks.run_hooks`.

The ``hooks.toml`` fixtures use the exact block shape the Nix renderer emits
(``schema = 1``, float ``timeout``/``retry_delay``), so a rendering change that
breaks the parser shows up here too.

Run from the repository root::

    .venv/bin/python -m pytest tests/test_hooks.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

# Make the package importable when run with a bare interpreter (no venv).
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from tartarus.config import Config, load_config  # noqa: E402
from tartarus.errors import TartarusError  # noqa: E402
from tartarus.hooks import Hook, load_hooks, run_hooks, substitute  # noqa: E402

# Generated-format ``hooks.toml``: header + one host-wide block with every
# field spelled out, exactly as `nix/host/hooks.nix` writes it (including the
# float `timeout`/`retry_delay` and the description line).
GENERATED_HOOKS_TOML = """\
# Generated by tartarus (nix/host/hooks.nix). Do not edit.
schema = 1

[[hooks]]
event = "start"
phase = "after"
command = "/nix/store/hash-rex-tunnel/bin/rex-tunnel up {name}"
guests = ["*"]
kinds = ["vm", "container"]
timeout = 20.0
retries = 15
retry_delay = 2.0
on_failure = "warn"
description = "Bring up the Rex tunnel"
"""


def make_config(tmp_path: Path, hooks: list[Hook] | None = None) -> Config:
    """A minimal resolved Config carrying *hooks*, rooted at *tmp_path*."""
    return Config(
        user="user",
        home_dir=tmp_path,
        flake_path=tmp_path / "nixcfg",
        system="aarch64-linux",
        state_root=tmp_path / "state",
        ssh_dir=tmp_path / ".ssh",
        ssh_ca_dir=tmp_path / "ssh-ca",
        x509_ca_dir=tmp_path / "x509-ca",
        hooks=list(hooks or []),
    )


def write_toml(path: Path, text: str) -> Path:
    path.write_text(text)
    return path


def hook(**overrides) -> Hook:
    """One start.after hook matching everything, with per-test overrides."""
    fields = {
        "event": "start",
        "phase": "after",
        "command": "true",
        "guests": ["*"],
        "kinds": ["vm", "container"],
        "timeout": 10.0,
        "retries": 0,
        "retry_delay": 0.0,
        "on_failure": "warn",
        "description": None,
    }
    fields.update(overrides)
    return Hook(**fields)


# --- load_hooks ------------------------------------------------------------


def test_load_hooks_parses_generated_format(tmp_path):
    path = write_toml(tmp_path / "hooks.toml", GENERATED_HOOKS_TOML)

    hooks = load_hooks(path)

    assert len(hooks) == 1
    (parsed,) = hooks
    assert parsed.event == "start"
    assert parsed.phase == "after"
    assert parsed.command == "/nix/store/hash-rex-tunnel/bin/rex-tunnel up {name}"
    assert parsed.guests == ["*"]
    assert parsed.kinds == ["vm", "container"]
    assert parsed.timeout == 20.0
    assert isinstance(parsed.timeout, float)
    assert parsed.retries == 15
    assert parsed.retry_delay == 2.0
    assert isinstance(parsed.retry_delay, float)
    assert parsed.on_failure == "warn"
    assert parsed.description == "Bring up the Rex tunnel"


def test_load_hooks_preserves_file_order(tmp_path):
    path = write_toml(
        tmp_path / "hooks.toml",
        """\
schema = 1

[[hooks]]
event = "start"
phase = "before"
command = "first"

[[hooks]]
event = "start"
phase = "before"
command = "second"
""",
    )

    assert [h.command for h in load_hooks(path)] == ["first", "second"]


def test_load_hooks_omitted_description_is_none(tmp_path):
    # The renderer drops the `description` line entirely when it is null.
    path = write_toml(
        tmp_path / "hooks.toml",
        """\
schema = 1

[[hooks]]
event = "stop"
phase = "before"
command = "true"
""",
    )

    (parsed,) = load_hooks(path)
    assert parsed.description is None
    # Defaults are the same ones the Nix option declares.
    assert parsed.guests == ["*"]
    assert parsed.kinds == ["vm", "container"]
    assert parsed.on_failure == "warn"


