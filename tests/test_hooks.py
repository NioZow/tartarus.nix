# --- hooks path precedence -------------------------------------------------


def write_config(path: Path, *, home: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'home = "{home}"\nsystem = "aarch64-linux"\nschema = 2\n')
    return path


def test_cli_hooks_flag_wins_over_env_and_sibling(tmp_path, monkeypatch):
    config_dir = tmp_path / "cfg"
    config_path = write_config(config_dir / "config.toml", home=tmp_path)
    write_toml(config_dir / "hooks.toml", 'schema = 1\n\n[[hooks]]\nevent = "start"\nphase = "before"\ncommand = "sibling"\n')
    env_hooks = write_toml(tmp_path / "env-hooks.toml", 'schema = 1\n\n[[hooks]]\nevent = "start"\nphase = "before"\ncommand = "env"\n')
    cli_hooks = write_toml(tmp_path / "cli-hooks.toml", 'schema = 1\n\n[[hooks]]\nevent = "start"\nphase = "before"\ncommand = "cli"\n')
    monkeypatch.setenv("TARTARUS_HOOKS", str(env_hooks))

    config = load_config({"config": str(config_path), "hooks": str(cli_hooks)})

    assert config.hooks_path == cli_hooks
    assert [h.command for h in config.hooks] == ["cli"]


